"""Download Skills England Occupations in Demand 2025 and write the web app's demand table.

    python scripts/fetch/oid_demand.py              # download (if missing) + regenerate
    python scripts/fetch/oid_demand.py --overwrite  # re-download the release ZIP

Reads supporting-files/occupations_by_demand.csv (one row per 4-digit SOC 2020) and writes
apps/web/src/occupationDemand.ts. The source covers the UK (ASHE-based indicators GB only).
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import zipfile

from _common import RAW, REPO, die, download, session

RELEASE_ZIP = (
    "https://content.explore-education-statistics.service.gov.uk/api/releases/"
    "b20e696c-8f0a-4dcc-a1e2-3cb4b963ab80/files?fromPage=ReleaseDownloads"
)
CSV_NAME = "supporting-files/occupations_by_demand.csv"
OUT = REPO / "apps" / "web" / "src" / "occupationDemand.ts"
LEVELS = {
    "Critical demand": "Critical",
    "Elevated demand": "Elevated",
    "Not in high demand": "Not in high demand",
}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--overwrite", action="store_true")
    args = ap.parse_args()

    zip_path = download(session(), RELEASE_ZIP, RAW / "oid" / "oid_2025.zip", overwrite=args.overwrite)
    with zipfile.ZipFile(zip_path) as z:
        rows = list(csv.DictReader(io.TextIOWrapper(z.open(CSV_NAME), encoding="utf-8-sig")))

    demand: dict[str, str] = {}
    for row in rows:
        if row["year"] != "2025":
            continue
        level = LEVELS.get(row["demand_level"])
        if level is None:
            die(f"unknown demand level {row['demand_level']!r} for SOC {row['soc20_unit']}")
        demand[row["soc20_unit"]] = level
    if len(demand) < 300:
        die(f"only {len(demand)} occupations found; check the release layout")

    body = "\n".join(f"  {json.dumps(soc)}: {json.dumps(level)}," for soc, level in sorted(demand.items()))
    OUT.write_text(
        "// Generated by scripts/fetch/oid_demand.py from Skills England, Occupations in Demand 2025\n"
        "// (occupations_by_demand.csv). Do not edit by hand; rerun the script.\n"
        "export type DemandLevel = \"Critical\" | \"Elevated\" | \"Not in high demand\";\n\n"
        f"export const occupationDemand: Record<string, DemandLevel> = {{\n{body}\n}};\n"
    )
    print(f"  wrote {OUT.relative_to(REPO)} ({len(demand)} occupations)")


if __name__ == "__main__":
    main()
